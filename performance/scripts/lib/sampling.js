/**
 * 샘플링 규칙 — "요청(또는 시드 데이터)을 어느 항목에 보낼 것인가"를 한 곳에 모은다.
 *
 * 이 파일이 따로 있는 이유는 두 가지다.
 *
 *   1. **중복 제거.** 예전에는 같은 Zipf 근사식이 `scripts/lib/data.js`(부하 생성)와
 *      `datasets/seed.js`(시드 생성) 두 곳에 글자까지 똑같이 복제돼 있었다. 그래서 index 0을
 *      못 뽑는 버그(S-03)가 부하 쪽과 데이터 쪽에 **동시에** 존재했고, 한쪽만 고치면
 *      "가장 인기 있는 글을 조회했는데 댓글이 0건"인 모순이 생길 참이었다. 규칙은 하나만
 *      존재해야 한다.
 *   2. **테스트 가능성.** k6 런타임 API(`k6/data`, `k6/execution`)를 import하지 않는 순수
 *      ESM이라 Node가 `await import()`로 그대로 로드할 수 있다(thresholds.js·phases.js와
 *      같은 성질). 덕분에 `tools/test/sampling.test.js`가 알고리즘을 **복사하지 않고**
 *      실제 구현을 불러 검증한다 — 복사하면 구현과 테스트가 사이좋게 같이 틀린다.
 *
 * 난수원을 인자로 받는 이유: k6는 `Math.random`을, 테스트와 `seed.js`는 고정 시드 LCG를
 * 넘긴다. 시드 데이터의 재현성(seed.js의 `rand()`)을 유지하면서 같은 분포 규칙을 쓰려면
 * 난수원이 주입 가능해야 한다.
 *
 * ── 왜 게시글과 페이지에 다른 함수를 쓰는가 ──────────────────────────────────
 * 게시글은 개수가 500~500,000으로 변하는 집합이라 분포를 **파라미터(s)로** 지정해야 한다.
 * 게시판 페이지는 값이 0~4 다섯 개뿐이라 **비율을 직접 적는 편이** 정확하고, 읽는 사람이
 * 눈으로 검산할 수 있다. 페이지까지 Zipf 수식 하나로 처리하면 "왜 1페이지가 19%인가"에
 * 답하려고 매번 수식을 다시 풀어야 한다.
 */

/**
 * Zipf 지수 s. 값이 클수록 상위 항목 집중도가 커진다.
 *
 * **데이터셋 크기와 무관하게 고정한다.** 크기별로 s를 다시 풀어 "상위 10% = 80%"를 억지로
 * 맞추면(그러려면 n=500에서 1.262, n=100,000에서 1.000이 필요하다) 데이터 크기와 트래픽
 * 규칙이 **동시에** 바뀌어, 실행 간 성능 차이를 어느 쪽 탓으로도 돌릴 수 없게 된다.
 * 비교 실험의 전제는 "규칙을 고정한 채 크기만 바꾼다"이다.
 *
 * 그래서 s를 고정하면 상대 집중도(상위 10% 비율)는 n에 따라 움직인다. 그건 버그가 아니라
 * 멱법칙의 성질이며, 오히려 실험에서 보고 싶은 현상이다 — 코퍼스가 커질수록 같은 **절대
 * 개수**의 워킹셋(예: 상위 200개)이 덮는 트래픽 비중이 줄어든다(88% → 65% → 56%).
 * 그쪽이 캐시·버퍼풀 적중률과 직결되므로, 검증도 `headShare(n, 200)`으로 한다.
 */
export const HOT_SKEW = 1.07;

/**
 * 게시판 목록 페이지 0~4의 목표 비율.
 *
 * **근거: 아직 실측이 아니라 가정이다.** 운영 액세스 로그가 없어 "첫 페이지 이탈이
 * 지배적"이라는 업계 통념에 기댔다. ALB/Nginx 로그가 쌓이면 실제 페이지 분포로 교체할 것.
 * 성능 시스템에서 가장 위험한 건 틀린 숫자가 아니라 근거 없이 확정된 것처럼 보이는 숫자다.
 *
 * 이 배열은 0~4페이지, 즉 OFFSET 0~40만 다룬다. **깊은 페이지의 OFFSET 비용은 여기서
 * 측정하지 않는다** — 일반 트래픽에 깊은 페이지 꼬리를 섞으면 그 꼬리가 p95를 얼마나
 * 끌어올렸는지 분리할 수 없다. 목적이 다른 측정이므로 별도 진단 시나리오로 잰다.
 */
export const PAGE_WEIGHTS = Object.freeze([0.55, 0.20, 0.12, 0.08, 0.05]);

/**
 * 인기 편중 인덱스 샘플러 — 0 이상 n 미만의 정수를 돌려주며, 0에 가까울수록 자주 뽑힌다.
 * 호출부는 배열이 인기순으로 정렬돼 있다고 가정한다(`posts.json`은 index 0 = 최고 인기글).
 *
 * 절단 멱법칙 P(랭크 r) ∝ 1/r^s 의 연속 근사에 대한 역누적분포다. 랭크는 1부터 시작하므로
 * 마지막에 1을 빼서 배열 인덱스로 바꾼다. 상수 시간이고 표를 만들지 않아 n=500,000에서도
 * 메모리를 쓰지 않는다.
 *
 * **폐기한 대안 1 — 기존 `floor(n^(u^1.7))` 근사.** u < 1이라 결과가 항상 1 이상이어서
 * index 0을 구조적으로 뽑지 못했다(S-03). 뒤의 `% n`도 값이 n에 닿지 못해 무효 연산이었다.
 *
 * **폐기한 대안 2 — 그 식에 -1만 하기.** 치역이 1..n-1이므로 1을 빼면 0..n-2가 되어,
 * 이번엔 **마지막 인덱스**가 사라진다. 방향만 반대인 같은 off-by-one이다.
 *
 * **폐기한 대안 3 — 누적 확률표 + 이분 탐색(정확한 이산 Zipf).** 분포는 가장 정확하지만
 * n에 비례하는 표를 VU마다 만들어야 하고, 정작 이 실험이 요구하는 정밀도를 넘어선다.
 * 연속 근사와의 차이는 꼬리 쪽 소수점 수준이라 병목 재현에 영향이 없다.
 */
export function hotIndex(n, s = HOT_SKEW, rng = Math.random) {
  // 데이터셋 로드 실패(빈 배열)를 조용히 넘기지 않는다. 예전 seed.js가 실패한 작업을 말없이
  // 버려 "성공 500건"으로 보고했던 것과 같은 종류의 사고를 여기서 막는다.
  if (!Number.isInteger(n) || n < 1) {
    throw new Error(`hotIndex: n은 1 이상의 정수여야 한다 (받은 값: ${n}) — 데이터셋이 비었는지 확인할 것`);
  }
  const u = rng();
  const x = isUnitExponent(s)
    ? Math.pow(n + 1, u)
    : Math.pow((Math.pow(n + 1, 1 - s) - 1) * u + 1, 1 / (1 - s));
  // 부동소수 오차로 x가 경계를 아주 조금 넘을 수 있다. 양쪽 다 조인다 —
  // 한쪽만 조이면 드물게 -1이나 n이 새어 나가고, 그건 표본 수백만 건에 한 번씩 터진다.
  return Math.min(Math.max(Math.floor(x), 1), n) - 1;
}

/**
 * `hotIndex`가 상위 m개(index 0 .. m-1)를 고를 이론적 확률. 닫힌 식이다.
 *
 * 테스트가 기대값을 **구현을 복사하지 않고** 계산하기 위해 존재한다. 몬테카를로 표본이
 * 이 값에 수렴하는지 보면, 샘플러와 이 식이 동시에 같은 방향으로 틀리지 않는 한 회귀가 잡힌다.
 * 리포트에서 "이 실행의 상위 200개 집중도" 같은 설명을 붙일 때도 쓸 수 있다.
 */
export function headShare(n, m, s = HOT_SKEW) {
  if (!Number.isInteger(n) || n < 1) throw new Error(`headShare: n은 1 이상의 정수여야 한다 (받은 값: ${n})`);
  const k = Math.min(Math.max(m, 0), n);
  if (k === 0) return 0;
  if (isUnitExponent(s)) return Math.log(k + 1) / Math.log(n + 1);
  return (Math.pow(k + 1, 1 - s) - 1) / (Math.pow(n + 1, 1 - s) - 1);
}

/** s=1은 위 식의 분모가 0이 되는 특이점이라 로그 형태로 갈라진다. */
function isUnitExponent(s) {
  return Math.abs(s - 1) < 1e-9;
}

/**
 * 가중치 배열에서 인덱스 하나를 뽑는다. 항목이 다섯 개뿐이라 선형 누적 탐색으로 충분하다.
 *
 * 가중치 합이 1이라고 가정하되 강제하지는 않는다. 대신 마지막 항목으로 떨어지게 두고,
 * 합이 1인지는 테스트가 상수를 직접 검사한다 — 런타임에 정규화해 버리면 오타가 조용히
 * 흡수되어 "선언한 비율"과 "실제 비율"이 어긋난 채로 실행된다.
 */
export function weightedIndex(weights, rng = Math.random) {
  const u = rng();
  let acc = 0;
  for (let i = 0; i < weights.length - 1; i++) {
    acc += weights[i];
    if (u < acc) return i;
  }
  return weights.length - 1;
}

/** 게시판 목록 페이지 번호(0~4) — `PAGE_WEIGHTS` 비율을 그대로 따른다. */
export function pageIndex(rng = Math.random) {
  return weightedIndex(PAGE_WEIGHTS, rng);
}
